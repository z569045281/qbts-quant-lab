"""📜 新闻推送附「以前追这种消息的结果」—— 2026-10-08 用户点单。

起因:10-08 反问时用户说,9-08 买 QBTX 是**看到新闻**(CHIPS 最高 $1 亿)才买的,
不是看仪表盘;而且他**主要看推送,很少开网页**。所以证据得送进推送里,出现在他
最想下单的那一刻 —— 放在网页上的回测表,下单那一刻他看不到。

━━ 纪律 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
· **只附证据,不新造信号。**「看新闻买」在 mining.md 判死过三次(第 28 / 43 / 44 轮)。
  这里展示的是那个已判死家族的基准成绩,用途是让人下单前看一眼,不给方向。
· 只在**利好**消息(或向上跳空)时附。坏消息后的抄底是另一回事,这里的数字不适用。

━━ 数字从哪来 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
QBTS 日线 2021-10-08 → 2026-10-07(1,254 天),**开盘价买入**:
  · 当天口径 = 当天收盘卖;与第 28 轮「开→收」分档表同一口径(那张表扣了 0.4% 成本,
    这里不扣,所以 3–8% 档是 33% 而不是 32%)
  · 20 天口径 = 第 20 个交易日收盘卖,**去掉重叠事件**(与上一个入选事件间隔 ≤20 天的不算),
    否则一波连涨会被数好几次
2026-10-08 核对。样本慢变,每年复核一次即可。

                    当天收盘            拿 20 天
  开盘涨 3–8%    n=166  33% 赚     n=39  中位 −10.8%  36% 赚
  开盘涨 ≥8%     n=37   51% 赚     n=18  中位 −0.6%   50% 赚
  随便哪天(对照)n=1254 42% 赚     n=59  中位 +0.3%   53% 赚

20 天的**均值**是正的(3–8% 档 +7.1%),因为少数几次涨了好几倍。推送里给中位和赚钱
比例而不给均值:中位描述的是「通常会怎样」,均值描述的是「偶尔会怎样」。
"""

from __future__ import annotations

# (下界, 上界 or None, 标签, 当天n, 当天赚钱率, 20天n, 20天中位, 20天赚钱率)
BANDS: list[tuple] = [
    (0.03, 0.08, "开盘涨 3–8%", 166, 0.33, 39, -0.108, 0.36),
    (0.08, None, "开盘涨 ≥8%", 37, 0.51, 18, -0.006, 0.50),
]
BASE_20D_WIN = 0.53       # 随便哪天开盘买、拿 20 天
CHECKED = "2026-10-08"


def _band(change: float) -> tuple | None:
    for b in BANDS:
        lo, hi = b[0], b[1]
        if change >= lo and (hi is None or change < hi):
            return b
    return None


def line(change: float | None) -> str:
    """给推送正文的一行。`change` = QBTS 相对上一收盘的涨跌(小数,0.069 = +6.9%)。

    · 涨 ≥3% → 只给对上的那一档(今天就是这种情况)
    · 涨不到 3% / 不知道 → 两档都给(消息还没反映到价格上,先告诉他跳空之后通常怎样)"""
    b = _band(change) if isinstance(change, (int, float)) else None
    if b is not None:
        _, _, lab, n0, w0, n20, m20, w20 = b
        if w20 >= 0.45:                      # ≥8% 档:20 天和抛硬币一样
            tail = f"拿 20 天 {w20:.0%} 赚 —— 抛硬币"
        else:
            tail = (f"拿 20 天中位 {m20:+.1%},只有 {w20:.0%} 赚"
                    f"(随便哪天买是 {BASE_20D_WIN:.0%})")
        return (f"📜 现在 {change:+.1%}。以前 QBTS {lab}的 {n0} 天,开盘买:"
                f"当天收盘 {w0:.0%} 赚;{tail}。")
    a, b2 = BANDS
    return ("📜 追消息的历史(QBTS 5 年,开盘买、拿 20 天):"
            f"{a[2]} → 中位 {a[6]:+.1%}、{a[7]:.0%} 赚;"
            f"{b2[2]} → {b2[7]:.0%} 赚。随便哪天买是 {BASE_20D_WIN:.0%}。")


FOOTER = "(第 28 / 43 / 44 轮判死:追消息不赚钱。数字是历史,不是预测)"


def block(change: float | None) -> str:
    """推送用的两行:基准 + 出处。"""
    return f"{line(change)}\n{FOOTER}"


if __name__ == "__main__":
    # 自检:三种输入都得出一行、绝不抛;档位边界是左闭右开
    print(block(0.069))
    print(block(0.12))
    print(block(0.01))
    print(block(None))
    assert _band(0.03)[2] == "开盘涨 3–8%" and _band(0.08)[2] == "开盘涨 ≥8%"
    assert _band(0.0299) is None and _band(-0.05) is None
    assert "抛硬币" in line(0.10)
    assert "36%" in line(0.05) and "53%" in line(0.05)
    print("news_history self-check OK")
